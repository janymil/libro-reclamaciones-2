/** Runs a tool defensively: a failing tool must not break the whole turn. */
async function safetyRunTool(
  name: string,
  args: Record<string, unknown>,
  context: AgentContext,
): Promise<AgentToolOutcome> {
  try {
    return await executeAgentTool(name, args, context);
  } catch (error) {
    console.error(`Agent tool "${name}" failed:`, error);
    return { toolName: name, result: { error: `La herramienta ${name} no pudo completarse.` } };
  }
}

function finalizeReply(
  content: string | null | undefined,
  toolsUsed: string[],
  citations: LegalCitation[],
): AgentReply {
  const reply = (content ?? "").trim();
  return {
    reply: reply || "No se generó una respuesta. Intente reformular la pregunta.",
    source: "ai",
    toolsUsed: [...new Set(toolsUsed)],
    citations: dedupeCitations(citations),
    model: AGENT_MODEL,
  };
}

/**
 * Deterministic answer used when no AI provider is configured: grounds the reply
 * in the local legal corpus so the endpoint (and its UI) stays useful.
 */
function fallbackReply(history: AgentMessage[]): AgentReply {
  const lastUserMessage = [...history].reverse().find((message) => message.role === "user")?.content ?? "";
  const matches = searchLegalKnowledge(lastUserMessage, 3);

  const body =
    matches.length > 0
      ? "Estas referencias normativas pueden serle útiles:\n\n" +
        matches
          .map((match) => `• ${match.entry.norm} — ${match.entry.article}: ${match.entry.summary}`)
          .join("\n\n")
      : "No encontré normativa relacionada directamente con su consulta en la base local.";

  return {
    reply:
      `${body}\n\n` +
      "(Nota: el proveedor de IA no está configurado [AI_API_KEY], así que respondo con las referencias " +
      "normativas locales. Configure un proveedor para obtener respuestas conversacionales y análisis de sus datos.)",
    source: "fallback",
    toolsUsed: ["buscar_normativa"],
    citations: matches.map((match) => match.citation),
    model: AGENT_MODEL,
  };
}

/**
 * Runs one turn of the co-pilot: sends the conversation (with the tools) to the
 * model, executes any tool calls against the tenant-scoped tools, feeds the
 * results back, and returns the final answer plus the citations it used.
 *
 * The function never throws: on any provider error it returns an explanatory
 * `fallback` reply so the UI always has something to show.
 */
export async function runAgent(context: AgentContext, messages: AgentMessage[]): Promise<AgentReply> {
  const history: AgentMessage[] = messages
    .filter(
      (message) =>
        (message.role === "user" || message.role === "assistant") &&
        typeof message.content === "string" &&
        message.content.trim().length > 0,
    )
    .slice(-MAX_HISTORY_MESSAGES)
    .map((message) => ({ role: message.role, content: message.content.slice(0, MAX_MESSAGE_CHARS) }));

  if (history.length === 0) {
    return {
      reply: "¿En qué puedo ayudarle sobre su Libro de Reclamaciones o la normativa de INDECOPI?",
      source: "fallback",
      toolsUsed: [],
      citations: [],
      model: AGENT_MODEL,
    };
  }

  const ai = getAIClient();
  if (!ai) {
    return fallbackReply(history);
  }

  const conversation: OpenAI.ChatCompletionMessageParam[] = [
    { role: "system", content: buildSystemPrompt(context) },
    ...history,
  ];

  const toolsUsed: string[] = [];
  const citations: LegalCitation[] = [];

  try {
    for (let step = 0; step < MAX_AGENT_STEPS; step += 1) {
      const response = await ai.chat.completions.create({
        model: AGENT_MODEL,
        messages: conversation,
        tools: AGENT_TOOLS,
        tool_choice: "auto",
        temperature: 0.2,
      });

      const message = response.choices[0]?.message;
      if (!message) break;

      conversation.push({
        role: "assistant",
        content: message.content ?? "",
        tool_calls: message.tool_calls,
      });

      const toolCalls = (message.tool_calls ?? []).filter((call) => call.type === "function");
      if (toolCalls.length === 0) {
        return finalizeReply(message.content, toolsUsed, citations);
      }

      for (const call of toolCalls) {
        const args = safeParseArguments(call.function.arguments);
        const outcome = await safetyRunTool(call.function.name, args, context);
        toolsUsed.push(outcome.toolName);
        if (outcome.citations) citations.push(...outcome.citations);
        conversation.push({
          role: "tool",
          tool_call_id: call.id,
          content: serializeToolResult(outcome.result),
        });
      }
    }

    // Step budget exhausted: force a final answer without offering tools again.
    const finalResponse = await ai.chat.completions.create({
      model: AGENT_MODEL,
      messages: conversation,
      temperature: 0.2,
    });
    return finalizeReply(finalResponse.choices[0]?.message?.content, toolsUsed, citations);
  } catch (error) {
    console.error("Error running compliance agent:", error);
    return {
      reply:
        "No se pudo completar la consulta con el proveedor de IA en este momento. " +
        "Intente nuevamente o reformule la pregunta.",
      source: "fallback",
      toolsUsed: [...new Set(toolsUsed)],
      citations: dedupeCitations(citations),
      model: AGENT_MODEL,
    };
  }
}

/** Describes the agent for the UI: provider state, tools and corpus size. */
export function agentCapabilities() {
  const status = getAIStatus();
  return {
    enabled: status.enabled,
    model: AGENT_MODEL,
    tools: AGENT_TOOLS.map((tool) => ({
      name: tool.function.name,
      description: tool.function.description,
    })),
    knowledgeBaseSize: LEGAL_KNOWLEDGE.length,
  };
}

export const agentService = {
  chat: (context: AgentContext, messages: AgentMessage[]) => runAgent(context, messages),
  capabilities: agentCapabilities,
};





