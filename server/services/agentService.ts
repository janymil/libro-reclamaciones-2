/**
 * Computes the legal deadline information for one complaint. Pure and exported so
 * it can be unit tested and reused: the model must never do this arithmetic.
 */
export function buildDeadlineInfo(complaint: Complaint, now: Date = new Date()): DeadlineInfo {
  const responseDate = complaint.responseDate ?? null;
  return {
    correlativo: complaint.correlativeNumber,
    fechaPresentacion: formatCalendarDate(complaint.submissionDate),
    fechaVencimiento: formatCalendarDate(complaint.dueDate),
    diasHabilesRestantes: businessDayCalculator.getRemainingBusinessDays(complaint.dueDate, now),
    vencido: businessDayCalculator.isComplaintOverdue(complaint.submissionDate, responseDate ?? undefined, now),
    fechaRespuesta: responseDate ? formatCalendarDate(responseDate) : null,
  };
}

/**
 * The asset-scoped, PII-minimized view of a complaint handed to the model. The
 * consumer's name, document, address, phone and email are deliberately excluded:
 * the agent works from the correlativo and the narrative, not from raw PII.
 */
function toComplaintSummary(complaint: Complaint, now: Date) {
  const deadline = buildDeadlineInfo(complaint, now);
  return {
    correlativo: complaint.correlativeNumber,
    tipo: complaint.complaintType,
    estado: complaint.status,
    prioridad: complaint.priority,
    producto: complaint.productServiceName,
    fechaPresentacion: deadline.fechaPresentacion,
    fechaVencimiento: deadline.fechaVencimiento,
    diasHabilesRestantes: deadline.diasHabilesRestantes,
    vencido: deadline.vencido,
  };
}

/** Locates a complaint within a single business by its correlative number. */
async function findComplaintByCorrelative(
  businessId: string,
  correlativo: string,
): Promise<Complaint | undefined> {
  const target = correlativo.trim().toLowerCase();
  if (!target) return undefined;
  const complaints = await storage.getComplaintsByBusiness(businessId);
  return complaints.find((complaint) => complaint.correlativeNumber.toLowerCase() === target);
}

const COMPLAINT_STATUSES = new Set(["new", "in_progress", "responded", "resolved", "overdue"]);
const COMPLAINT_TYPES = new Set(["reclamo", "queja"]);
const COMPLAINT_PRIORITIES = new Set(["low", "normal", "high", "urgent"]);

/**
 * Returns the value only when it matches one of the allowed options. Guards the
 * data tools against unexpected strings and nulls from the model.
 */
function pickAllowed(value: unknown, allowed: Set<string>): string | undefined {
  return typeof value === "string" && allowed.has(value) ? value : undefined;
}

function clampLimit(value: unknown): number {
  const parsed =
    typeof value === "number" && Number.isFinite(value) ? Math.floor(value) : DEFAULT_COMPLAINT_LIMIT;
  return Math.min(Math.max(parsed, 1), MAX_COMPLAINT_LIMIT);
}

function safeParseArguments(raw: string | undefined): Record<string, unknown> {
  if (!raw) return {};
  try {
    const parsed = JSON.parse(raw);
    return parsed && typeof parsed === "object" && !Array.isArray(parsed)
      ? (parsed as Record<string, unknown>)
      : {};
  } catch {
    return {};
  }
}

function serializeToolResult(result: unknown): string {
  let serialized: string;
  try {
    serialized = JSON.stringify(result);
  } catch {
    serialized = JSON.stringify({ error: "Resultado no serializable." });
  }
  return serialized.length > MAX_TOOL_RESULT_CHARS
    ? `${serialized.slice(0, MAX_TOOL_RESULT_CHARS)}…`
    : serialized;
}

function dedupeCitations(citations: LegalCitation[]): LegalCitation[] {
  const seen = new Set<string>();
  return citations.filter((citation) => {
    if (seen.has(citation.id)) return false;
    seen.add(citation.id);
    return true;
  });
}

/**
 * Executes one tool call. `context` carries the authenticated tenant: every data
 * tool is scoped to `context.businessId` and there is no way for the model to
 * change it.
 */
export async function executeAgentTool(
  name: string,
  args: Record<string, unknown>,
  context: AgentContext,
): Promise<AgentToolOutcome> {
  switch (name) {
    case "buscar_normativa": {
      const query = typeof args.consulta === "string" ? args.consulta : "";
      const matches = searchLegalKnowledge(query, 4);
      return {
        toolName: name,
        citations: matches.map((match) => match.citation),
        result: {
          resultados: matches.map((match) => ({
            id: match.entry.id,
            norma: match.entry.norm,
            articulo: match.entry.article,
            titulo: match.entry.title,
            contenido: match.entry.summary,
          })),
          nota:
            matches.length === 0
              ? "No se encontraron normas relacionadas con la consulta. Reformule los términos."
              : undefined,
        },
      };
    }

    case "consultar_reclamos": {
      const estado = pickAllowed(args.estado, COMPLAINT_STATUSES);
      const tipo = pickAllowed(args.tipo, COMPLAINT_TYPES);
      const prioridad = pickAllowed(args.prioridad, COMPLAINT_PRIORITIES);
      const limit = clampLimit(args.limite);

      const complaints = await storage.getComplaintsByBusiness(context.businessId, {
        status: estado,
        type: tipo,
        priority: prioridad,
      });
      const now = new Date();
      const byDeadline = [...complaints].sort(
        (a, b) => a.dueDate.getTime() - b.dueDate.getTime(),
      );

      return {
        toolName: name,
        result: {
          total: complaints.length,
          mostrados: Math.min(limit, byDeadline.length),
          reclamos: byDeadline.slice(0, limit).map((complaint) => toComplaintSummary(complaint, now)),
        },
      };
    }

    case "resumen_caso": {
      const correlativo = typeof args.correlativo === "string" ? args.correlativo : "";
      const complaint = await findComplaintByCorrelative(context.businessId, correlativo);
      if (!complaint) {
        return {
          toolName: name,
          result: {
            error: `No se encontró la reclamación ${correlativo} en esta cuenta. Verifique el número correlativo.`,
          },
        };
      }

      // Consumer PII (name, document, address, phone, email) is intentionally
      // omitted: the summary is built from the narrative and the case metadata.
      const caseText = [
        `Correlativo: ${complaint.correlativeNumber}`,
        `Tipo: ${complaint.complaintType} (prioridad ${complaint.priority})`,
        `Estado: ${complaint.status}`,
        `Producto/Servicio: ${complaint.productServiceName}`,
        `Detalle: ${complaint.complaintDetail}`,
        `Pedido del consumidor: ${complaint.consumerRequest ?? "No especificado"}`,
        `Respuesta enviada: ${complaint.providerResponse ?? "Aún sin respuesta"}`,
      ].join("\n");

      const summary = await aiService.generateCaseSummary(caseText);
      return {
        toolName: name,
        result: {
          correlativo: complaint.correlativeNumber,
          plazo: buildDeadlineInfo(complaint),
          resumen: summary.summary,
          hechosClave: summary.keyFacts,
          riesgo: summary.riskLevel,
          accionRecomendada: summary.recommendedAction,
          fuente: summary.source,
        },
      };
    }

    case "calcular_plazo": {
      const correlativo = typeof args.correlativo === "string" ? args.correlativo : "";
      const complaint = await findComplaintByCorrelative(context.businessId, correlativo);
      if (!complaint) {
        return {
          toolName: name,
          result: {
            error: `No se encontró la reclamación ${correlativo} en esta cuenta. Verifique el número correlativo.`,
          },
        };
      }
      return {
        toolName: name,
        result: {
          tipo: complaint.complaintType,
          estado: complaint.status,
          ...buildDeadlineInfo(complaint),
        },
      };
    }

    case "estado_cumplimiento": {
      const report = await legalComplianceService.generateComplianceReport(context.businessId);
      return {
        toolName: name,
        result: {
          estadoGeneral: report.overallStatus,
          incumplimientosCriticos: report.criticalIssues,
          accionesPendientes: report.pendingActions,
          controles: report.complianceChecks.map((check) => ({
            tipo: check.type,
            estado: check.status,
            descripcion: check.description,
            vencimiento: check.dueDate ? formatCalendarDate(check.dueDate) : null,
          })),
          recomendaciones: report.recommendations,
        },
      };
    }

    case "estadisticas_reclamos": {
      const stats = await storage.getComplaintStats(context.businessId);
      return {
        toolName: name,
        result: {
          total: stats.total,
          nuevos: stats.new,
          enProceso: stats.inProgress,
          respondidos: stats.responded,
          resueltos: stats.resolved,
          vencidos: stats.overdue,
          cumplimientoSla: stats.slaCompliance,
          tiempoPromedioRespuestaHoras: stats.avgResponseTime,
        },
      };
    }

    default:
      return { toolName: name, result: { error: `Herramienta desconocida: ${name}` } };
  }
}

