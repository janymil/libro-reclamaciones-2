/**
 * Compliance co-pilot ("Copiloto de Cumplimiento").
 *
 * A domain-scoped, tool-calling agent for the Libro de Reclamaciones. Unlike a
 * general chatbot, the model is never the source of truth:
 *
 *  - The law comes from a curated, human-reviewed corpus
 *    (`@shared/legal-knowledge`, tool `buscar_normativa`).
 *  - Legal deadlines are computed by `businessDayCalculator`, never by the model
 *    (tool `calcular_plazo`).
 *  - The tenant's data is read through hard-scoped tools: every tool receives the
 *    authenticated `businessId` from the route context and can only ever touch
 *    that business's records. The model cannot name another business.
 *
 * The provider is the same OpenAI-compatible client as the rest of the AI
 * features (`aiService`), so any configured provider (Groq free tier, OpenRouter,
 * DeepSeek, Ollama, ...) works without further changes. When no provider is
 * configured the agent degrades to a deterministic answer built from the local
 * legal corpus.
 */

export interface AgentContext {
  businessId: string;
  businessName?: string | null;
  userId: string;
  userName: string;
}

export interface AgentMessage {
  role: "user" | "assistant";
  content: string;
}

export interface AgentReply {
  reply: string;
  /** 'ai' = generated by the model, 'fallback' = local heuristics/corpus. */
  source: "ai" | "fallback";
  /** Tool names the agent invoked, in order, without duplicates. */
  toolsUsed: string[];
  /** Normative references the answer is grounded in. */
  citations: LegalCitation[];
  model: string;
}

export interface DeadlineInfo {
  correlativo: string;
  fechaPresentacion: string;
  fechaVencimiento: string;
  diasHabilesRestantes: number;
  vencido: boolean;
  fechaRespuesta: string | null;
}

interface AgentToolOutcome {
  toolName: string;
  result: unknown;
  citations?: LegalCitation[];
}

